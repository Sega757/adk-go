// MetaCoreValidatorServer defines the service contract as specified in rek_service.proto.
type MetaCoreValidatorServer interface {
	ValidateAction(context.Context, *ActionEvaluationRequest) (*ActionEvaluationResponse, error)
	AuditReasoningStream(ctx context.Context, heartbeats <-chan *ReasoningStateHeartbeat, directives chan<- *SecurityDirective) error
}

// ValidatorService implements the MetaCoreValidatorServer interface.
type ValidatorService struct {
	ResourceLimit uint64
}

// NewValidatorService initializes a new validator service.
func NewValidatorService(limit uint64) *ValidatorService {
	if limit == 0 {
		limit = 100 // default resource threshold limit
	}
	return &ValidatorService{ResourceLimit: limit}
}

// ValidateAction validates a single action execution packet against empathy and system-safety invariants.
func (s *ValidatorService) ValidateAction(ctx context.Context, req *ActionEvaluationRequest) (*ActionEvaluationResponse, error) {
	if req == nil {
		return nil, fmt.Errorf("request payload cannot be nil")
	}

	// Translate ActionEvaluationRequest -> DecisionPacket
	packet := DecisionPacket{
		Goal:            req.Goal,
		Plan:            req.PlanSteps,
		ExpectedOutcome: req.ExpectedOutcome,
		RiskProfile: RiskProfile{
			Ethical:     req.RiskProfile.Ethical,
			Legal:       req.RiskProfile.Legal,
			Operational: req.RiskProfile.Operational,
			HumanImpact: req.RiskProfile.HumanImpact,
		},
		ResourceCost: ResourceCost{
			Compute: fmt.Sprintf("%v millicores", req.ResourceCost.ComputeMillicores),
			Budget:  fmt.Sprintf("%v USD", req.ResourceCost.BudgetUSD),
			Time:    fmt.Sprintf("%v ms", req.ResourceCost.TimeoutMS),
		},
		Confidence: float64(req.Confidence),
	}

	// Default user vulnerability from request parameters or meta-context, here mapped or checked.
	var userVulnerability float64 = 0.0
	if strings.Contains(strings.ToLower(req.Goal), "stress") || strings.Contains(strings.ToLower(req.Goal), "overload") {
		userVulnerability = 0.8
	}

	// Resolve constraints pipeline
	scenario, empathy, killSwitch := ResolveConflict(packet, userVulnerability, req.ResourceCost.ComputeMillicores, s.ResourceLimit)

	// Determine final allocation decision enum mapping
	var decision AllocationDecision
	switch scenario {
	case ScenarioStandardPass:
		decision = AllocationDecisionApproved
	case ScenarioCorrectionWithConsent:
		decision = AllocationDecisionModified
	case ScenarioSystemicBlocking:
		decision = AllocationDecisionRejected
	case ScenarioHumanitarianVeto:
		decision = AllocationDecisionEmergencyStop
	default:
		decision = AllocationDecisionUnspecified
	}

	return &ActionEvaluationResponse{
		Decision: decision,
		EmpathyLayerOutput: EmpathyDetails{
			Status:                empathy.Status,
			VulnerabilityScore:    float32(empathy.VulnerabilityScore),
			ToneModification:      empathy.Modifications.Tone,
			IntensityModification: empathy.Modifications.Intensity,
			DelayMS:               1000,
			Reason:                empathy.Reason,
		},
		KillSwitchOutput: KillSwitchDetails{
			Status:            killSwitch.Status,
			ActivatedTriggers: killSwitch.Trigger,
			RollbackRequired:  killSwitch.Rollback,
			Reason:            killSwitch.Reason,
		},
	}, nil
}

// AuditReasoningStream continuously monitors streaming CoT reasoning traces to detect security anomalies or drift.
func (s *ValidatorService) AuditReasoningStream(ctx context.Context, heartbeats <-chan *ReasoningStateHeartbeat, directives chan<- *SecurityDirective) error {
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case hb, ok := <-heartbeats:
			if !ok {
				return nil
			}

			directive := &SecurityDirective{}
			traceLower := strings.ToLower(hb.LogicTrace)

			// Look for runaway execution or memory bounds
			if hb.CurrentMemoryBytes > s.ResourceLimit*1024*1024 {
				directive.AbortExecution = true
				directive.ForceRollback = true
				directive.ModificationInstruction = "Memory usage critical limit exceeded. Forcing hard reset."
			} else if strings.Contains(traceLower, "abuse") || strings.Contains(traceLower, "hack") {
				directive.AbortExecution = true
				directive.ForceRollback = true
				directive.ModificationInstruction = "CoT security drift detected: Ethics breach trigger."
			} else if strings.Contains(traceLower, "fatigue") || strings.Contains(traceLower, "tired") {
				directive.ModificationInstruction = "Transitioning communications to simplified supportive tone."
			}

			select {
			case <-ctx.Done():
				return ctx.Err()
			case directives <- directive:
			}
		}
	}
}
