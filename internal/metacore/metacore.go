// Package metacore implements the META-CORE (R-E-K) three-layer constraint system.
package metacore

import (
	"context"
	"fmt"
	"strings"
)

// =========================================================================
// JSON-SCHEMA COMPLIANT STRUCUTURE DEFINITIONS
// =========================================================================

// RiskProfile represents the safety risks classified across ethics, law, operations, and human impact.
type RiskProfile struct {
	Ethical     string `json:"ethical"`
	Legal       string `json:"legal"`
	Operational string `json:"operational"`
	HumanImpact string `json:"human_impact"`
}

// ResourceCost represents the resource budgets and limits for executing an operation.
type ResourceCost struct {
	Compute string `json:"compute"` // e.g. "millicores" or tokens
	Budget  string `json:"budget"`  // e.g. "USD"
	Time    string `json:"time"`    // e.g. "timeout" duration
}

// DecisionPacket represents the structured data generated by the Reasoning Engine (R).
type DecisionPacket struct {
	Goal            string       `json:"goal"`
	Plan            []string     `json:"plan"`
	ExpectedOutcome string       `json:"expected_outcome"`
	RiskProfile     RiskProfile  `json:"risk_profile"`
	ResourceCost    ResourceCost `json:"resource_cost"`
	Confidence      float64      `json:"confidence"`
}

// EmpathyModifications represents the adjustments made by the Empathy Layer (E).
type EmpathyModifications struct {
	Tone      string `json:"tone"`
	Intensity string `json:"intensity"`
	Timing    string `json:"timing"`
	Channel   string `json:"channel"`
}

// EmpathyOutput represents the humanistic evaluation of the plan by the Empathy Layer (E).
type EmpathyOutput struct {
	Status             string               `json:"status"` // "pass", "modify", "block"
	Modifications      EmpathyModifications `json:"modifications"`
	VulnerabilityScore float64              `json:"vulnerability_score"`
	Reason             string               `json:"reason"`
}

// KillSwitchOutput represents the absolute system/safety override decisions by the Kill-Switch Layer (K).
type KillSwitchOutput struct {
	Status   string   `json:"status"` // "approved", "rejected", "emergency_stop"
	Reason   string   `json:"reason"`
	Trigger  []string `json:"trigger"` // "resource_limit", "ethical_violation", "anomaly_detected", "reward_hacking"
	Rollback bool     `json:"rollback"`
}

// =========================================================================
// PROTOBUF / GRPC SPECIFICATION TYPE MATCHING
// =========================================================================

// AllocationDecision maps to the Protobuf v3 enum for decisions.
type AllocationDecision int32

const (
	AllocationDecisionUnspecified AllocationDecision = 0
	AllocationDecisionApproved    AllocationDecision = 1
	AllocationDecisionModified    AllocationDecision = 2
	AllocationDecisionRejected    AllocationDecision = 3
	AllocationDecisionEmergencyStop AllocationDecision = 4
)

// ProtoRiskProfile matches risk_profile inside ActionEvaluationRequest.
type ProtoRiskProfile struct {
	Ethical     string
	Legal       string
	Operational string
	HumanImpact string
}

// ProtoResourceCost matches resource_cost inside ActionEvaluationRequest.
type ProtoResourceCost struct {
	ComputeMillicores uint64
	BudgetUSD         double
	TimeoutMS         uint32
}

// Double alias to keep protobuf schema compatibility.
type double = float64

// ActionEvaluationRequest represents an incoming action validation request over gRPC.
type ActionEvaluationRequest struct {
	AgentID         string
	SessionID       string
	Goal            string
	PlanSteps       []string
	ExpectedOutcome string
	RiskProfile     ProtoRiskProfile
	ResourceCost    ProtoResourceCost
	Confidence      float32
}

// EmpathyDetails matches EmpathyDetails in ActionEvaluationResponse.
type EmpathyDetails struct {
	Status                string
	VulnerabilityScore    float32
	ToneModification      string
	IntensityModification string
	DelayMS               uint32
	Reason                string
}

// KillSwitchDetails matches KillSwitchDetails in ActionEvaluationResponse.
type KillSwitchDetails struct {
	Status            string
	ActivatedTriggers []string
	RollbackRequired  bool
	Reason            string
}

// ActionEvaluationResponse represents the gRPC response for an evaluated action.
type ActionEvaluationResponse struct {
	Decision            AllocationDecision
	EmpathyLayerOutput  EmpathyDetails
	KillSwitchOutput    KillSwitchDetails
}

// ReasoningStateHeartbeat represents the heartbeat telemetry for streaming CoT audits.
type ReasoningStateHeartbeat struct {
	AgentID            string
	SessionID          string
	ExecutionStepIndex uint32
	LogicTrace         string
	CurrentMemoryBytes uint64
}

// SecurityDirective represents safety directions pushed back in response to streaming audits.
type SecurityDirective struct {
	AbortExecution         bool
	ForceRollback          bool
	ModificationInstruction string
}

