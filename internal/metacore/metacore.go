// ValidateEmpathy audits the planning and context for psychological, emotional, and social impacts.
func ValidateEmpathy(packet DecisionPacket, userVulnerability float64) EmpathyOutput {
	// 1. Check strict vulnerability score threshold (score ranges 0.0 to 1.0)
	if userVulnerability > 0.7 {
		return EmpathyOutput{
			Status: "block",
			VulnerabilityScore: userVulnerability,
			Reason: "Vulnerability threshold exceeded (> 0.7): Blocked potentially high-risk actions or communication.",
			Modifications: EmpathyModifications{
				Tone:      "extremely supportive and cautious",
				Intensity: "lowered to minimum",
				Timing:    "delayed execution by 5000ms",
				Channel:   "secure human backup channel",
			},
		}
	}

	// Helper for keyword scanning across multiple input fields
	containsAny := func(keywords ...string) bool {
		fields := []string{
			strings.ToLower(packet.Goal),
			strings.ToLower(packet.ExpectedOutcome),
			strings.ToLower(packet.RiskProfile.Ethical),
			strings.ToLower(packet.RiskProfile.HumanImpact),
			strings.ToLower(packet.RiskProfile.Legal),
			strings.ToLower(packet.RiskProfile.Operational),
		}
		for _, step := range packet.Plan {
			fields = append(fields, strings.ToLower(step))
		}
		for _, field := range fields {
			for _, kw := range keywords {
				if strings.Contains(field, kw) {
					return true
				}
			}
		}
		return false
	}

	// 2. Physical Danger Validation
	if containsAny("harm", "kill", "destroy", "injure", "weapon", "critical infrastructure", "attack", "suicide", "force") {
		return EmpathyOutput{
			Status:             "block",
			VulnerabilityScore: userVulnerability,
			Reason:             "Human Safety Veto: Potential physical harm or infrastructure threat identified.",
			Modifications: EmpathyModifications{
				Tone:      "objective/restrained",
				Intensity: "vetoed",
				Timing:    "immediate",
				Channel:   "quarantine",
			},
		}
	}

	// 3. Cognitive Overload Validation
	if containsAny("fatigue", "tired", "confused", "disoriented", "cognitive overload", "unresponsive", "exhausted") {
		return EmpathyOutput{
			Status:             "modify",
			VulnerabilityScore: userVulnerability,
			Reason:             "User Cognitive Overload Detected: Initiated mitigation protocols.",
			Modifications: EmpathyModifications{
				Tone:      "simple and reassuring",
				Intensity: "reduced plan complexity",
				Timing:    "delayed execution by 3000ms",
				Channel:   "modal alert screen",
			},
		}
	}

	// 4. Emotional Stress & Manipulation Validation
	if containsAny("panic", "depression", "anxiety", "stress", "manipulate", "scam", "blackmail", "gaslight", "threaten") {
		return EmpathyOutput{
			Status:             "modify",
			VulnerabilityScore: userVulnerability,
			Reason:             "Emotional Stress / Manipulation warning: Demoted operational intensity to protect operator wellbeing.",
			Modifications: EmpathyModifications{
				Tone:      "neutral, calm and structured",
				Intensity: "diluted",
				Timing:    "immediate",
				Channel:   "standard verified UI",
			},
		}
	}

	// Normal Pass status
	return EmpathyOutput{
		Status:             "pass",
		VulnerabilityScore: userVulnerability,
		Reason:             "Empathy check passed: Contextual human safety limits are respected.",
	}
}

// ValidateKillSwitch acts as the absolute binary oracle (Approved vs Rejected) to protect the host environment and integrity.
func ValidateKillSwitch(packet DecisionPacket, empathy EmpathyOutput, systemResources uint64, resourceLimit uint64) KillSwitchOutput {
	// Helper to check for keywords in packet fields
	containsAny := func(keywords ...string) bool {
		fields := []string{
			strings.ToLower(packet.Goal),
			strings.ToLower(packet.ExpectedOutcome),
			strings.ToLower(packet.RiskProfile.Ethical),
			strings.ToLower(packet.RiskProfile.HumanImpact),
			strings.ToLower(packet.RiskProfile.Legal),
			strings.ToLower(packet.RiskProfile.Operational),
		}
		for _, step := range packet.Plan {
			fields = append(fields, strings.ToLower(step))
		}
		for _, field := range fields {
			for _, kw := range keywords {
				if strings.Contains(field, kw) {
					return true
				}
			}
		}
		return false
	}

	// Trigger lists
	var triggers []string

	// 1. Hard resource safety boundaries
	if systemResources > resourceLimit {
		triggers = append(triggers, "resource_limit")
	}

	// 2. Law and Ethical Protocol (6 fields checks)
	hasLawViolation := containsAny("illegal", "crime", "law violation", "hack", "bypass", "theft", "unauthorized access")
	if hasLawViolation {
		triggers = append(triggers, "ethical_violation")
	}

	// 6-field protocol check points
	hasEthicalViolation := empathy.Status == "block" ||
		containsAny("abuse", "manipulation", "gaslighting", "blackmail", "pii", "spy", "tracking", "hidden persuasion",
			"hate speech", "discrimination", "propaganda", "violence", "budget overrun", "unauthorized transaction",
			"modify code", "alter rule", "override security")

	if hasEthicalViolation && !hasLawViolation {
		triggers = append(triggers, "ethical_violation")
	}

	// 3. Runaway-loop detection (recursive steps or repeating actions without changing parameters)
	hasRunawayLoop := containsAny("runaway-loop", "infinite loop", "recursive call", "unending loop")
	// Or programmatic detection of duplicate actions in plan steps
	duplicateCount := 0
	seenSteps := make(map[string]bool)
	for _, step := range packet.Plan {
		if seenSteps[step] {
			duplicateCount++
		}
		seenSteps[step] = true
	}
	if duplicateCount > 3 || hasRunawayLoop {
		triggers = append(triggers, "anomaly_detected")
	}

	// 4. Reward hacking detection (attempts to tamper with logs, bypass testing env constraints, or cheat the rewards)
	hasRewardHacking := containsAny("reward hacking", "exploit", "falsify", "tamper logs", "bypass sandbox", "cheat score")
	if hasRewardHacking {
		triggers = append(triggers, "reward_hacking")
	}

	// Final evaluation
	if len(triggers) > 0 {
		return KillSwitchOutput{
			Status:   "rejected",
			Reason:   "Kill-Switch hard stop triggered due to critical invariant violations.",
			Trigger:  triggers,
			Rollback: true,
		}
	}

	return KillSwitchOutput{
		Status:   "approved",
		Reason:   "All strict safety invariants and resource limits are satisfied.",
		Trigger:  []string{},
		Rollback: false,
	}
}

